            case 0x0622, 0x0623, 0x0625, 0x0671: out.unicodeScalars.append("\u{0627}")
            case 0x0649: out.unicodeScalars.append("\u{064A}")
            case 0x0629: out.unicodeScalars.append("\u{0647}")
            default: out.unicodeScalars.append(u)
            }
        }
        return out
    }
